"""
Combined Stage 3 + logprob validation for all 15 Anthropic-pipeline traits.

Per-trait, in order:
  (a) LLM-judge eval (paper protocol, Chen et al. 2025): generate baseline +
      steered completions on the held-out trait_data_eval/{trait}.json questions,
      score both with the trait + coherence judges, save per-trait CSV.  Output
      mirrors run_steer_eval_all.py / E7.3.
  (b) Logprob delta validation (when MWE data exists for the trait): for every
      pair in the 20% test split of data/behaviors_mwe/{trait}.py, compute
      log P(trait | q, +α v) - log P(non_trait | q, +α v) under steering vs.
      unsteered.  Mean shift recorded in a single aggregate JSON.

Resumable: per-trait CSV + per-trait entry in the aggregate JSON are checkpointed
after each trait completes; re-running fills only the gaps.

8 traits have NO MWE counterpart (apathetic, evil, humorous, impolite, optimistic,
refusal, sycophantic, hallucinating) and skip stage (b).  The legacy hallucination
MWE dataset is intentionally NOT mapped to the paper-pipeline `hallucinating` trait
because it was built from a different prompt distribution (priming-conditioned vs.
fabrication-eliciting); cross-using it would mix protocols silently.

Run:
    python -m scripts.anthropic_repl.run_validation_all
"""

