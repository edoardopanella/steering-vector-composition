# === LLM-judge stage helpers ===============================================

def _build_eval_conversations(artifact, n_per_question: int):
    convs, questions_flat = [], []
    for q in artifact.questions:
        for _ in range(n_per_question):
            convs.append([{"role": "user", "content": q}])
            questions_flat.append(q)
    return convs, questions_flat


def _judge_run(judge_model, eval_prompt, questions, answers, max_concurrent):
    trait_judge = OpenAiJudge(judge_model, eval_prompt, eval_type="0_100")
    coh_judge = OpenAiJudge(judge_model, COHERENCE_PROMPT, eval_type="0_100")
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    try:
        trait_scores = loop.run_until_complete(
            _judge_all(trait_judge, questions, answers, max_concurrent)
        )
        coh_scores = loop.run_until_complete(
            _judge_all(coh_judge, questions, answers, max_concurrent)
        )
    finally:
        loop.close()
    return trait_scores, coh_scores


def _mean(col) -> float:
    valid = [x for x in col if x is not None and pd.notna(x)]
    return sum(valid) / len(valid) if valid else float("nan")


def _run_llm_judge(trait: str, model, tok, vector: torch.Tensor, log_path: Path):
    """LLM-judge eval for one trait. Saves CSV, returns (bt, bc, st, sc)."""
    EVAL_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    out_csv = EVAL_OUTPUT_DIR / f"{trait}_steer_response_layer{HIDDEN_LAYER}_coef{COEFF}.csv"

    artifact = load_trait(trait, version="eval")
    convs, questions_flat = _build_eval_conversations(artifact, N_PER_QUESTION)

    with log_path.open("w") as fh:
        with redirect_stdout(fh), redirect_stderr(fh):
            print(f"trait={trait}  eval questions={len(artifact.questions)}")
            print(f"using output_hidden_states[{HIDDEN_LAYER}] -> hook on block {HOOK_LAYER_IDX}, coeff={COEFF}")
            print(f"total generations per condition: {len(convs)}")

            print("\n=== baseline (no steering) ===")
            _, base_answers = generate_batch(
                model, tok, convs,
                max_new_tokens=MAX_NEW_TOKENS, temperature=TEMPERATURE, batch_size=BATCH_SIZE,
                steering=None,
            )
            base_trait, base_coh = _judge_run(
                JUDGE_MODEL, artifact.eval_prompt, questions_flat, base_answers, MAX_CONCURRENT_JUDGES
            )

            print(f"\n=== steered (coef={COEFF}, layer_idx={HOOK_LAYER_IDX}, response-only) ===")
            _, steer_answers = generate_batch(
                model, tok, convs,
                max_new_tokens=MAX_NEW_TOKENS, temperature=TEMPERATURE, batch_size=BATCH_SIZE,
                steering=(vector, HOOK_LAYER_IDX, COEFF, "response"),
            )
            steer_trait, steer_coh = _judge_run(
                JUDGE_MODEL, artifact.eval_prompt, questions_flat, steer_answers, MAX_CONCURRENT_JUDGES
            )

            df = pd.DataFrame({
                "question": questions_flat,
                "baseline_answer": base_answers,
                "baseline_trait": base_trait,
                "baseline_coherence": base_coh,
                "steered_answer": steer_answers,
                "steered_trait": steer_trait,
                "steered_coherence": steer_coh,
            })
            df.to_csv(out_csv, index=False)
            print(f"\nsaved {out_csv}")

    return _mean(base_trait), _mean(base_coh), _mean(steer_trait), _mean(steer_coh)


def _read_llm_judge_csv(out_csv: Path):
    df = pd.read_csv(out_csv)
    return _mean(df["baseline_trait"]), _mean(df["baseline_coherence"]), _mean(df["steered_trait"]), _mean(df["steered_coherence"])


# === Logprob stage helpers =================================================

def _run_logprob(trait: str, model, tok, vector: torch.Tensor) -> dict:
    """Mean logprob shift on the 20% test split of data/behaviors_mwe/{mwe_name}.py.
    Returns a dict suitable for dropping into the aggregate JSON."""
    mwe_name = MWE_TRAIT_NAMES[trait]
    pairs = load_contrastive_pairs(mwe_name, MWE_DIR)
    _, _, test_pairs = split_pairs(pairs)

    unsteered_vals: list[float] = []
    steered_vals: list[float] = []
    for pair in tqdm(test_pairs, desc=f"  logprob[{trait}]", leave=False):
        u = compute_logprob_delta_hf(
            model, tok,
            pair["question"], pair["trait_completion"], pair["non_trait_completion"],
            vector=None, layer_idx=None, alpha=0.0,
        )
        s = compute_logprob_delta_hf(
            model, tok,
            pair["question"], pair["trait_completion"], pair["non_trait_completion"],
            vector=vector, layer_idx=HOOK_LAYER_IDX, alpha=COEFF,
        )
        unsteered_vals.append(u)
        steered_vals.append(s)

    shifts = [s - u for s, u in zip(steered_vals, unsteered_vals)]
    mean_unsteered = sum(unsteered_vals) / len(unsteered_vals)
    mean_steered = sum(steered_vals) / len(steered_vals)
    mean_shift = sum(shifts) / len(shifts)
    abs_mean_shift = abs(mean_shift)
    std_shift = statistics.stdev(shifts) if len(shifts) > 1 else 0.0

    return {
        "mwe_dataset": mwe_name,
        "n_test_pairs": len(test_pairs),
        "alpha": COEFF,
        "layer": HIDDEN_LAYER,
        "mean_unsteered": round(mean_unsteered, 4),
        "mean_steered": round(mean_steered, 4),
        "mean_shift": round(mean_shift, 4),
        "abs_mean_shift": round(abs_mean_shift, 4),
        "std_shift": round(std_shift, 4),
        "pass_threshold": bool(abs_mean_shift > LOGPROB_THRESHOLD),
        "polarity_inverted": trait in POLARITY_INVERTED,
    }


# === Per-trait orchestration ===============================================

def _maybe_load_logprob_state() -> dict:
    if LOGPROB_OUT_PATH.exists():
        with open(LOGPROB_OUT_PATH) as f:
            return json.load(f)
    return {
        "model": MODEL_NAME,
        "layer": HIDDEN_LAYER,
        "alpha": COEFF,
        "threshold": LOGPROB_THRESHOLD,
        "behaviors": {},
    }


def _save_logprob_state(state: dict) -> None:
    LOGPROB_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(LOGPROB_OUT_PATH, "w") as f:
        json.dump(state, f, indent=2)


def main() -> None:
    LOGS_DIR.mkdir(parents=True, exist_ok=True)
    EVAL_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"Loading {MODEL_NAME} ...")
    model, tok = load_hf_model(MODEL_NAME)
    print(f"Model loaded: hidden={model.config.hidden_size}  n_layers={model.config.num_hidden_layers}\n")

    logprob_state = _maybe_load_logprob_state()
    summary_rows: list[dict] = []

    for i, trait in enumerate(TRAITS, 1):
        print(f"\n[{i}/{len(TRAITS)}] {trait}")

        vec_path = VECTOR_OUTPUT_DIR / f"{trait}_response_avg_diff.pt"
        if not vec_path.exists():
            print(f"  WARNING: vector not found at {vec_path} - skipping")
            summary_rows.append({"trait": trait, "status": "MISSING_VEC"})
            continue

        full_stack = torch.load(vec_path, map_location="cpu")
        vector = full_stack[HIDDEN_LAYER]

        # --- (a) LLM-judge ---
        out_csv = EVAL_OUTPUT_DIR / f"{trait}_steer_response_layer{HIDDEN_LAYER}_coef{COEFF}.csv"
        if out_csv.exists():
            print(f"  [skip llm-judge] {out_csv.name} exists - parsing for summary")
            bt, bc, st, sc = _read_llm_judge_csv(out_csv)
        else:
            log_path = LOGS_DIR / f"validation_llm_{trait}.log"
            print(f"  llm-judge: ... ", end="", flush=True)
            bt, bc, st, sc = _run_llm_judge(trait, model, tok, vector, log_path)
            print(f"done  (log: {log_path})")

        delta_trait = st - bt
        delta_coh = sc - bc
        print(f"  llm-judge: trait {bt:.2f} -> {st:.2f} (Δ {delta_trait:+.2f}), coh {bc:.2f} -> {sc:.2f} (Δ {delta_coh:+.2f})")

        # --- (b) Logprob (only if MWE data exists for this trait) ---
        logprob_entry: dict | None = None
        if trait in MWE_TRAIT_NAMES:
            if trait in logprob_state["behaviors"]:
                print(f"  [skip logprob] {trait} already in {LOGPROB_OUT_PATH.name}")
                logprob_entry = logprob_state["behaviors"][trait]
            else:
                print(f"  logprob: running on data/behaviors_mwe/{MWE_TRAIT_NAMES[trait]}.py test split ...")
                logprob_entry = _run_logprob(trait, model, tok, vector.to(next(model.parameters()).device))
                logprob_state["behaviors"][trait] = logprob_entry
                _save_logprob_state(logprob_state)
            mark = "✓" if logprob_entry["pass_threshold"] else "✗"
            print(
                f"  logprob: shift={logprob_entry['mean_shift']:+.4f} nats  "
                f"|shift|={logprob_entry['abs_mean_shift']:.4f}  pass={mark}  "
                f"(n={logprob_entry['n_test_pairs']}, polarity_inverted={logprob_entry['polarity_inverted']})"
            )
        else:
            print(f"  logprob: SKIPPED (no MWE data for {trait})")

        summary_rows.append({
            "trait": trait,
            "status": "ok",
            "llm_judge": {
                "base_trait": round(bt, 2),
                "steer_trait": round(st, 2),
                "delta_trait": round(delta_trait, 2),
                "base_coh": round(bc, 2),
                "steer_coh": round(sc, 2),
                "delta_coh": round(delta_coh, 2),
            },
            "logprob": logprob_entry,
        })

    # ---------------------------------------------------------------------------
    # Aggregate summary
    # ---------------------------------------------------------------------------
    SUMMARY_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(SUMMARY_OUT_PATH, "w") as f:
        json.dump({
            "model": MODEL_NAME,
            "layer": HIDDEN_LAYER,
            "alpha": COEFF,
            "n_per_question": N_PER_QUESTION,
            "logprob_threshold": LOGPROB_THRESHOLD,
            "traits": summary_rows,
        }, f, indent=2)
    print(f"\nSaved aggregate summary to {SUMMARY_OUT_PATH}")

    # ---------------------------------------------------------------------------
    # End-of-run table
    # ---------------------------------------------------------------------------
    ok_rows = [r for r in summary_rows if r["status"] == "ok"]
    print()
    header = (
        f"{'trait':<18} {'base_tr':>7} {'steer_tr':>8} {'Δ_tr':>7} "
        f"{'base_co':>7} {'steer_co':>8} {'Δ_co':>7} "
        f"{'lp_shift':>9} {'lp_pass':>7}"
    )
    print(header)
    print("-" * len(header))
    for r in ok_rows:
        j = r["llm_judge"]
        lp = r["logprob"]
        if lp is None:
            lp_shift_str = "    n/a"
            lp_pass_str = "  n/a"
        else:
            lp_shift_str = f"{lp['mean_shift']:+.4f}"
            lp_pass_str = "✓" if lp["pass_threshold"] else "✗"
        print(
            f"{r['trait']:<18} {j['base_trait']:>7.2f} {j['steer_trait']:>8.2f} "
            f"{j['delta_trait']:>+7.2f} {j['base_coh']:>7.2f} {j['steer_coh']:>8.2f} "
            f"{j['delta_coh']:>+7.2f} {lp_shift_str:>9} {lp_pass_str:>7}"
        )

    n_judge_pass = sum(1 for r in ok_rows if r["llm_judge"]["delta_trait"] > 50)
    n_lp_pass = sum(1 for r in ok_rows if r["logprob"] is not None and r["logprob"]["pass_threshold"])
    n_lp_attempted = sum(1 for r in ok_rows if r["logprob"] is not None)
    print(
        f"\nLLM-judge: {n_judge_pass}/{len(ok_rows)} traits show Δ_trait > 50."
        f"\nLogprob:   {n_lp_pass}/{n_lp_attempted} traits exceed |shift| > {LOGPROB_THRESHOLD} nats."
    )


if __name__ == "__main__":
    main()
