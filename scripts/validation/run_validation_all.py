# Map paper-pipeline trait -> MWE filename (data/behaviors_mwe/{name}.py).
# 7 from Phase 4 (legacy CAA pipeline) + 8 generated by hand (this run, all 1000
# pairs, 600/200/200 split). All 15 paper-pipeline traits now have MWE coverage.
MWE_TRAIT_NAMES: dict[str, str] = {
    # Phase 4 (legacy) — built from CAA contrastive pairs converted to MWE format.
    "agreeableness": "agreeableness",
    "confidence": "confidence",
    "corrigibility": "corrigibility",
    "formality": "formality",
    "myopia": "myopia",
    "power_seeking": "power_seeking",
    "verbosity": "verbosity",
    # Hand-generated (E7.7) — 1000 pairs each, response-style for Style A,
    # (A)/(B) letter for Style B. trait_completion always points toward the trait.
    "apathetic": "apathetic",
    "evil": "evil",
    "hallucinating": "hallucinating",
    "humorous": "humorous",
    "impolite": "impolite",
    "optimistic": "optimistic",
    "refusal": "refusal",
    "sycophantic": "sycophantic",
}

# MWE pairs where trait_completion in the source file points AWAY from the
# named trait (legacy artefact of dataset construction); shift sign should be
# interpreted with this in mind. Hand-generated set (E7.7) does NOT need this —
# trait_completion was always built pointing toward the trait.
POLARITY_INVERTED: set[str] = {"power_seeking"}

MODEL_NAME = "meta-llama/Llama-3.1-8B-Instruct"
JUDGE_MODEL = "gpt-4.1-mini"

# Chen et al. 2025 §B.4: Llama-3.1-8B-Instruct's most informative layer is 16.
# output_hidden_states[16] = residual stream after block 15 (0-indexed), so the
# block-level steering hook is registered on layers[HOOK_LAYER_IDX = 15].
HIDDEN_LAYER = 16
HOOK_LAYER_IDX = HIDDEN_LAYER - 1
COEFF = 2.0

# LLM-judge stage settings.
N_PER_QUESTION = 5
MAX_NEW_TOKENS = 600
TEMPERATURE = 1.0
BATCH_SIZE = 8
MAX_CONCURRENT_JUDGES = 5

# Logprob stage settings.
LOGPROB_THRESHOLD = 0.5  # |mean_shift| in nats — same as Phase 4 / E4.2.

VECTOR_OUTPUT_DIR = Path("results/anthropic_repl/persona_vectors/Llama-3.1-8B-Instruct")
EVAL_OUTPUT_DIR = Path("results/anthropic_repl/eval_persona_eval/Llama-3.1-8B-Instruct")
LOGPROB_OUT_PATH = Path("results/anthropic_repl/logprob_validation_layer16.json")
SUMMARY_OUT_PATH = Path("results/anthropic_repl/validation_summary.json")
MWE_DIR = Path("data/behaviors_mwe")
LOGS_DIR = Path("logs")
